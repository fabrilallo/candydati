import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DESCRIPTIONS } from './descriptions.mjs';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (path) => readFileSync(join(ROOT, path), 'utf8');

/** Keys declared as `  NAME: z...` in a Zod env schema source file. */
const schemaKeys = (path) =>
  [...read(path).matchAll(/^ {2}([A-Z][A-Z0-9_]+):(.*)$/gm)].map(([, name, rest]) => ({
    name,
    fallback: /\.default\(([^)]*)\)/.exec(rest)?.[1]?.replace(/^'|'$/g, '') ?? '',
  }));

/** Provider keys the assistant knows (`PROVIDER_KEYS` in the agent config). */
const providerKeys = () =>
  [...read('apps/api/src/agent/config.ts').matchAll(/: '([A-Z][A-Z0-9_]*_API_KEY)'/g)].map(([, name]) => ({ name, fallback: '' }));

/** `runtimeConfig` of Nuxt: `apiInternalUrl` is `NUXT_API_INTERNAL_URL`, `public.timeZone` is `NUXT_PUBLIC_TIME_ZONE`. */
const webKeys = () => {
  const block = /runtimeConfig:\s*\{([\s\S]*?)\n {2}\},/.exec(read('apps/web/nuxt.config.ts'))?.[1] ?? '';
  const snake = (key) => key.replace(/([A-Z])/g, '_$1').toUpperCase();
  const names = [];
  let inPublic = false;
  for (const line of block.split('\n')) {
    if (/^\s{4}public:/.test(line)) inPublic = true;
    else if (/^\s{4}\}/.test(line)) inPublic = false;
    const key = /^\s{4}([a-zA-Z]+):/.exec(line)?.[1] ?? (inPublic ? /^\s{6}([a-zA-Z]+):/.exec(line)?.[1] : undefined);
    if (key && key !== 'public') names.push({ name: `NUXT_${inPublic ? 'PUBLIC_' : ''}${snake(key)}`, fallback: '' });
  }
  return names;
};

const shared = () => [
  ...schemaKeys('packages/providers/src/storage/config.ts'),
  ...schemaKeys('packages/providers/src/email/config.ts'),
  ...schemaKeys('packages/domain/src/platform/config.ts'),
];

const SOURCES = {
  api: () => [...schemaKeys('apps/api/src/config/env.ts'), ...shared(), ...providerKeys()],
  worker: () => [...schemaKeys('apps/worker/src/config/env.ts'), ...shared(), ...providerKeys()],
  web: webKeys,
};

/** Every variable with the processes that read it. */
export function collectVariables() {
  const byName = new Map();
  for (const [app, load] of Object.entries(SOURCES)) {
    for (const { name, fallback } of load()) {
      const entry = byName.get(name) ?? { name, apps: [], fallback };
      if (!entry.apps.includes(app)) entry.apps.push(app);
      byName.set(name, entry);
    }
  }
  return [...byName.values()].sort((a, b) => a.name.localeCompare(b.name));
}

export function renderEnvDocs() {
  const variables = collectVariables();
  const missing = variables.filter((v) => !DESCRIPTIONS[v.name]).map((v) => v.name);
  if (missing.length > 0) throw new Error(`Missing description in tools/env-docs/descriptions.mjs: ${missing.join(', ')}`);
  const rows = variables.map(
    (v) => `| \`${v.name}\` | ${v.apps.join(', ')} | ${v.fallback ? `\`${v.fallback}\`` : ''} | ${DESCRIPTIONS[v.name]} |`,
  );
  return [
    '# Environment variables',
    '',
    '<!-- Generated by `pnpm --filter @tt/tools env-docs` from the Zod env schemas. Do not edit by hand: a test fails when it is stale. -->',
    '',
    'Every variable read by the api, the worker and the web app. Empty values count as unset. The `.env.example` file has working',
    'development values; `docker-compose.prod.yml` passes the same names to the containers.',
    'Variables without a default are required or optional as described; see `.env.example`.',
    '',
    '| Variable | Read by | Default | Meaning |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}
