import type { AdQualityReport, JobContent, JobStatus } from '@tt/domain';
import { sql } from 'drizzle-orm';
import { index, integer, jsonb, pgTable, text, timestamp, uniqueIndex } from 'drizzle-orm/pg-core';
import { organization } from './auth.js';

/**
 * The job ad (PLAN §5). `content` is validated with `jobContentSchema` when read: jsonb is a boundary.
 * `organization_id` is RESTRICT like the audit log: an organization with ads is archived, never hard-deleted.
 * `created_by` is plain text with no foreign key, so ads survive the removal of the user who wrote them.
 */
export const job = pgTable(
  'job',
  {
    /** Generated by the application (uuid). */
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organization.id, { onDelete: 'restrict' }),
    /** Public URL segment, unique inside the organization, never changes. */
    slug: text('slug').notNull(),
    status: text('status').$type<JobStatus>().notNull().default('draft'),
    /** Copy of `content.title`, for listings. */
    title: text('title').notNull(),
    content: jsonb('content').$type<JobContent>().notNull(),
    quality: jsonb('quality').$type<AdQualityReport>(),
    createdBy: text('created_by').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
    publishedAt: timestamp('published_at', { withTimezone: true }),
    closedAt: timestamp('closed_at', { withTimezone: true }),
    /** Approval of the budget (PLAN Phase 9): all five are set together, or none. Written by `approvals`, never by `jobs.save`. */
    approvalApprovedBy: text('approval_approved_by'),
    approvalApprovedAt: timestamp('approval_approved_at', { withTimezone: true }),
    approvalSalaryMin: integer('approval_salary_min'),
    approvalSalaryMax: integer('approval_salary_max'),
    approvalCurrency: text('approval_currency'),
  },
  (table) => [
    uniqueIndex('job_org_slug_uidx').on(table.organizationId, table.slug),
    index('job_org_status_updated_at_idx').on(table.organizationId, table.status, sql`${table.updatedAt} desc`),
  ],
);

export const jobTemplate = pgTable(
  'job_template',
  {
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organization.id, { onDelete: 'restrict' }),
    name: text('name').notNull(),
    content: jsonb('content').$type<JobContent>().notNull(),
    createdBy: text('created_by').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [index('job_template_org_idx').on(table.organizationId)],
);

export type JobRow = typeof job.$inferSelect;
export type NewJobRow = typeof job.$inferInsert;
export type JobTemplateRow = typeof jobTemplate.$inferSelect;
