import { sql } from 'drizzle-orm';
import { index, jsonb, pgTable, text, timestamp } from 'drizzle-orm/pg-core';
import { organization } from './auth.js';

/**
 * Append-only record of actions (see `AuditEvent` in @candydati/domain). UPDATE and DELETE are rejected by a
 * database trigger (custom migration), so the log cannot be edited even with direct database access.
 *
 * - `organization_id` references `organization` with ON DELETE RESTRICT: an organization that has history
 *   cannot be hard-deleted, so the log is never erased (cascade would be blocked by the trigger anyway, and
 *   SET NULL would be an UPDATE). Deleting an organization is a soft/archive operation at the app level.
 * - Actor and target ids are plain text with no foreign keys, so the log survives user/member deletion.
 */
export const auditLog = pgTable(
  'audit_log',
  {
    /** Generated by the application (uuid). */
    id: text('id').primaryKey(),
    organizationId: text('organization_id')
      .notNull()
      .references(() => organization.id, { onDelete: 'restrict' }),
    /** One of ACTOR_TYPES in @candydati/domain: user, agent, api_key, system. */
    actorType: text('actor_type').notNull(),
    actorId: text('actor_id'),
    onBehalfOfUserId: text('on_behalf_of_user_id'),
    /** One of AUDIT_ACTIONS in @candydati/domain. */
    action: text('action').notNull(),
    targetType: text('target_type').notNull(),
    targetId: text('target_id').notNull(),
    metadata: jsonb('metadata').$type<Record<string, unknown>>().notNull().default({}),
    occurredAt: timestamp('occurred_at', { withTimezone: true }).defaultNow().notNull(),
  },
  (table) => [
    index('audit_log_org_occurred_at_idx').on(table.organizationId, sql`${table.occurredAt} desc`),
    index('audit_log_org_action_occurred_at_idx').on(table.organizationId, table.action, sql`${table.occurredAt} desc`),
  ],
);

export type AuditLogRow = typeof auditLog.$inferSelect;
export type NewAuditLogRow = typeof auditLog.$inferInsert;
